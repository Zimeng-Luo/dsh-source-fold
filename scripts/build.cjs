function buildClient({ logic, ui, plugin, css }) {
  const body = [
    '"use strict";',
    'const React = require("react");',
    'const ReactDOM = require("react-dom");',
    logic.trim(),
    ui.trim(),
    "const CSS = " + JSON.stringify(css) + ";",
    "const ModelSeat = createIsland(React, ReactDOM);",
    plugin.trim(),
    'return { name: "dsh-source-fold", inject: ["slots", "modelDirectories", "sessions", "remote", "remote.session"], apply };'
  ].join("\n\n");
  return '// Copyright (c) 2026 Zimeng-Luo. MIT License.\n// Generated by scripts/build.cjs. Browser artifact: DSH classic-script module factory.\nwindow.__ModuleLoader__.load({\n  id: "dsh-source-fold",\n  factory: function (require) {\n'
    + body.split("\n").map(line => "    " + line).join("\n")
    + "\n  }\n});\n";
}

module.exports = { buildClient };

if (require.main === module) {
  const fs = require("node:fs");
  const path = require("node:path");
  const root = path.resolve(__dirname, "..");
  const read = name => fs.readFileSync(path.join(root, name), "utf8");
  const output = buildClient({
    logic: read("src/logic.js"), ui: read("src/island.js"),
    plugin: read("src/plugin.js"), css: read("src/island.css")
  });
  const target = path.join(root, "client.js");
  if (process.argv.includes("--check")) {
    if (fs.readFileSync(target, "utf8") !== output) {
      throw new Error("client.js is stale; run npm run build");
    }
  } else {
    fs.writeFileSync(target, output);
    console.log("Built client.js");
  }
}
